float score_eng_text(float freq[256], u64 total_chars)
{
    float score = 0;
    for (int i = 0; i < 256; i++) {
        freq[i] /= (float)total_chars;
        float dif = freq[i] - ascii_char_freq[i];
        if (dif < 0) {
            dif *= -1;
        }
        score += dif;
    }
    return score;
}


u8 decript_char_xor(StrView bytes, String* decoded)
{
    // temp holds temp text, decode stores the best scoring text
    String temp       = String_with_cap(decoded->alloc, decoded->capacity);
    float  best_score = 100000.0F;
    u8     best_key   = 255;

    for (int i = 0; i < 256; i++) { // for each 1-byte char
        String_clear(&temp);
        float freq[256] = {0};

        for (u64 j = 0; j < bytes.len; j++) {   // for each byte in the encoded string
            char c = (char)(bytes.data[j] ^ i); // decipher
            freq[(u8)c]++;
            String_append_char(&temp, c);
        }
        float score = score_eng_text(freq, bytes.len);
        if (score < best_score) {
            best_score = score;
            best_key   = (u8)i;
            String_clear(decoded);
            String_append_String(decoded, &temp);
        }
    }

    String_destroy(&temp);
    return best_key;
}


int challenge3_run(void)
{
    String hex = String_from_cstr(WC_LIBC, "1b37373331363f78151b7f2b783431333d78397828372d363c78373e783a393b3736");
    String_print(&hex);
    putchar('\n');

    String bytes = String_with_cap(WC_LIBC, String_len(&hex));
    hex_decode(StrView_over_String(&hex), &bytes);
    String_print(&bytes);
    putchar('\n');

    String decoded = String_with_cap(WC_LIBC, String_len(&bytes));
    decript_char_xor(StrView_over_String(&bytes), &decoded);
    String_print(&decoded);
    putchar('\n');

    String_destroy(&hex);
    String_destroy(&bytes);
    String_destroy(&decoded);
    return 0;
}
